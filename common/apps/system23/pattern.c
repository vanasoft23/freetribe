void pattern_place_note(t_pattern *ptn, int part_idx, int step_idx) {
    if (ptn->parts[part_idx].steps[step_idx].gate > 0) {
        ptn->parts[part_idx].steps[step_idx].gate = 0;
    } else {
        ptn->parts[part_idx].steps[step_idx].gate = GATE_FULL;
    }
}


