static gdb_command_result_t _handle_stop(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	(void)request;

	_reply_put(reply, 'S');
	_reply_put(reply, hex_digit((u8)gdb_monitor_get_stop_reason() >> 4));
	_reply_put(reply, hex_digit((u8)gdb_monitor_get_stop_reason()));

	return _send_reply();
}

static gdb_command_result_t _handle_continue(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	(void)request;
	
	gdb_command_result_t result = {
		.send_reply      = false,
		.action          = GDB_ACTION_CONTINUE,
		.protocol_change = GDB_PROTOCOL_UNCHANGED,
	};
	return result;
}

static gdb_command_result_t _handle_detach(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	(void)request;

	reply->data[0] = 'O';
	reply->data[1] = 'K';
	reply->len     =   2;

	gdb_command_result_t result = {
		.send_reply      = true,
		.action          = GDB_ACTION_DETACH,
		.protocol_change = GDB_PROTOCOL_UNCHANGED,
	};
	return result;
}

static gdb_command_result_t _handle_step(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	(void)request;
	
	if (!gdb_monitor_prepare_step()) {
		return _reply_error(server, request, reply, 1u);
	}

	gdb_command_result_t result = {
		.send_reply      = false,
		.action          = GDB_ACTION_STEP,
		.protocol_change = GDB_PROTOCOL_UNCHANGED,
	};
	return result;
}

static gdb_command_result_t _handle_insert_breakpoint(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	// @TODO: check if watchpoint or breakpoint

	const u8 *cursor = request.data + 1;
	const u8 *end    = request.data + request.len;
	u32       type; // 0 swbreak, 2 write watch, 3 read watch, 4 access watch
	u32       address;
	u32       kind;

	if (!_parse_hex_u32(&cursor, end, &type) ||
		(cursor == end) || (*cursor++ != ',') ||
		!_parse_hex_u32(&cursor, end, &address) ||
		(cursor == end) || (*cursor++ != ',') ||
		!_parse_hex_u32(&cursor, end, &kind) ||
		(cursor != end))
	{
		return _reply_error(server, request, reply, 0x01);
	}
		
	if (kind != 4u) {
		return _reply_error(server, request, reply, 0x01);
	}

	if (type != 0) { // 0 swbreak
		return _reply_error(server, request, reply, 0x01);
	}
	
	if (!gdb_monitor_insert_breakpoint(address)) {
		return _reply_error(server, request, reply, 1u);
	}

	reply->data[0] = 'O';
	reply->data[1] = 'K';
	reply->len     =   2;
	return _send_reply();
}

