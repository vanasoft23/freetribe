static bool _reply_put(gdb_reply_writer_t *reply, u8 byte) {

	if (reply->len >= reply->capacity) {
		reply->overflow = true;
		reply->len = 0;
		return false;
	}

	reply->data[reply->len++] = byte;
	return true;
}

static bool _reply_put_buf(gdb_reply_writer_t *reply, const u8 *buf, u32 len) {
	
	if ((reply->len > reply->capacity) ||
		(len > reply->capacity - reply->len)) {
		reply->overflow = true;
		reply->len = 0;
		return false;
	}

	memcpy(reply->data + reply->len, buf, len);
	reply->len += len;

	return true;
}

static bool _reply_put_str(gdb_reply_writer_t *reply, const char *str) {
	
	return _reply_put_buf(reply, (const u8*)str, strlen(str));
}

static void _append_hex_reg(char **pp_data, u32 reg_value) {
	hex_digits32(*pp_data, reg_value);
	*pp_data += 8;
}

static bool _parse_hex_u32(
	const u8 **cursor,
	const u8  *end,
	u32       *value
) {
	const u8 *position = *cursor;
	u32       parsed   = 0u;
	bool      has_digit = false;

	while (position < end) {
		int nibble = hex_nibble(*position);
		if (nibble < 0) {
			break;
		}
		if (parsed > (UINT32_MAX >> 4)) {
			return false;
		}
		parsed = (parsed << 4) | (u32)nibble;
		position++;
		has_digit = true;
	}

	if (!has_digit) {
		return false;
	}

	*cursor = position;
	*value  = parsed;
	return true;
}

