static gdb_command_result_t _handle_read_memory(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	enum { READ_CHUNK_SIZE = 32 };

	const u8 *cursor = request.data + 1;
	const u8 *end    = request.data + request.len;
	u32       address;
	u32       length;

	if (!_parse_hex_u32(&cursor, end, &address) ||
		(cursor == end) || (*cursor++ != ',') ||
		!_parse_hex_u32(&cursor, end, &length) ||
		(cursor != end)) {
		return _reply_error(server, request, reply, 0x01);
	}

	// Reject address wrap and replies that cannot fit before reading memory.
	if (((length != 0u) && (address > UINT32_MAX - (length - 1u))) ||
		(reply->len > reply->capacity) ||
		(length > (reply->capacity - reply->len) / 2u)) {
		return _reply_error(server, request, reply, 0x22);
	}

	gdb_memory_reader_t reader = server->memory_reader;
	if (reader == NULL) {
		reader = gdb_monitor_read_memory;
	}

	u8  bytes[READ_CHUNK_SIZE];
	u32 offset = 0u;
	while (offset < length) {
		u32 chunk_length = length - offset;
		if (chunk_length > (u32)sizeof(bytes)) {
			chunk_length = (u32)sizeof(bytes);
		}

		if (!reader(
				server->memory_reader_context,
				address + offset,
				bytes,
				chunk_length)) {
			reply->len = 0u;
			return _reply_error(server, request, reply, 0x14);
		}

		for (u32 i = 0u; i < chunk_length; ++i) {
			reply->data[reply->len++] = hex_digit(bytes[i] >> 4);
			reply->data[reply->len++] = hex_digit(bytes[i]);
		}
		offset += chunk_length;
	}

	return _send_reply();
}


// vibecoded
static gdb_command_result_t _handle_write_memory(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	enum { WRITE_CHUNK_SIZE = 32 };

	const u8 *cursor = request.data + 1;
	const u8 *end    = request.data + request.len;
	u32       address;
	u32       length;

	if (!_parse_hex_u32(&cursor, end, &address) ||
		(cursor == end) || (*cursor++ != ',') ||
		!_parse_hex_u32(&cursor, end, &length) ||
		(cursor == end) || (*cursor++ != ':')) {
		return _reply_error(server, request, reply, 0x01);
	}

	u32 encoded_length = (u32)(end - cursor);
	if (((encoded_length & 1u) != 0u) ||
		((encoded_length / 2u) != length)) {
		return _reply_error(server, request, reply, 0x01);
	}

	/* Validate every digit before allowing the first memory write. */
	for (const u8 *digit = cursor; digit < end; ++digit) {
		if (hex_nibble(*digit) < 0) {
			return _reply_error(server, request, reply, 0x01);
		}
	}

	if ((length != 0u) && (address > UINT32_MAX - (length - 1u))) {
		return _reply_error(server, request, reply, 0x22);
	}

	/* Do not modify memory when even the success response cannot fit. */
	if (reply->capacity < 2u) {
		reply->overflow = true;
		return _send_reply();
	}

	gdb_memory_writer_t writer = server->memory_writer;
	if (writer == NULL) {
		writer = gdb_monitor_write_memory;
	}

	u8  bytes[WRITE_CHUNK_SIZE];
	u32 offset = 0u;
	while (offset < length) {
		u32 chunk_length = length - offset;
		if (chunk_length > (u32)sizeof(bytes)) {
			chunk_length = (u32)sizeof(bytes);
		}

		for (u32 i = 0u; i < chunk_length; ++i) {
			u32 encoded_offset = (offset + i) * 2u;
			bytes[i] = (u8)(
				(hex_nibble(cursor[encoded_offset]) << 4) |
				hex_nibble(cursor[encoded_offset + 1u])
			);
		}

		if (!writer(
				server->memory_writer_context,
				address + offset,
				bytes,
				chunk_length)) {
			return _reply_error(server, request, reply, 0x14);
		}
		offset += chunk_length;
	}

	_reply_put_str(reply, "OK");
	return _send_reply();
}

