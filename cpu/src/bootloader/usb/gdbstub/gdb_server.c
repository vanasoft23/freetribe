static bool _monitor_next(
	monitor_parser_t *parser,
	monitor_token_t  *token
) {
	_monitor_skip_whitespace(parser);

	if (parser->cursor == parser->end) {
		return false;
	}

	const u8 *start = parser->cursor;
	while ((parser->cursor < parser->end) &&
		   (*parser->cursor != ' ') && (*parser->cursor != '\t')) {
		parser->cursor++;
	}

	token->data   = start;
	token->length = (u32)(parser->cursor - start);
	return true;
}

static void _monitor_skip_whitespace(monitor_parser_t *parser) {
	while ((parser->cursor < parser->end) &&
		   ((*parser->cursor == ' ') || (*parser->cursor == '\t'))) {
		parser->cursor++;
	}
}

static bool _monitor_done(monitor_parser_t *parser) {
	_monitor_skip_whitespace(parser);
	return parser->cursor == parser->end;
}

static bool _monitor_token_equals(
	monitor_token_t token,
	const char     *text
) {
	size_t text_length = strlen(text);
	return (text_length == token.length) &&
		   (memcmp(token.data, text, text_length) == 0);
}

static bool _monitor_parse_u32(
	monitor_token_t token,
	u32            *value
) {
	u32 position = 0u;
	u32 base     = 10u;
	u32 parsed   = 0u;

	if (token.length == 0u) {
		return false;
	}

	if ((token.length >= 2u) &&
		(token.data[0] == '0') &&
		((token.data[1] == 'x') || (token.data[1] == 'X'))) {
		position = 2u;
		base     = 16u;
	}

	if (position == token.length) {
		return false;
	}

	for (; position < token.length; ++position) {
		int digit = hex_nibble(token.data[position]);
		if ((digit < 0) || ((u32)digit >= base)) {
			return false;
		}

		if (parsed > (UINT32_MAX - (u32)digit) / base) {
			return false;
		}
		parsed = parsed * base + (u32)digit;
	}

	*value = parsed;
	return true;
}


