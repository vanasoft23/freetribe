gdb_command_result_t gdb_server_handle_req(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	reply->len   = 0;
	reply->overflow = false;

	if (request.len == 0) {
		return _reply_empty(server, request, reply);
	}
	
// #ifdef DEBUG
//     static char dbgstr[RSP_TX_CAPACITY];
//     memset(dbgstr, 0, sizeof(dbgstr));
//     memcpy(dbgstr, rsp->tx.payload, rsp->tx.len);
//     DLOG(dbgstr);
// #endif

	char *op = (char*)&request.data[0];

// parse:
	switch (*op) {
	case '?':
		return _handle_stop(server, request, reply);

	case 'c':
		return _handle_continue(server, request, reply);

	case 's':
		return _handle_step(server, request, reply);

	case 'Z':
		return _handle_insert_breakpoint(server, request, reply);

	case 'z':
		return _handle_remove_breakpoint(server, request, reply);

	case 'g':
		return _handle_read_registers(server, request, reply);

	// case 'G':
	//     return _handle_write_registers(server, request, reply);

	// case 'p':
	//     return _handle_read_register(server, request, reply);

	// case 'P':
	//     return _handle_write_register(server, request, reply);

	case 'm':
		return _handle_read_memory(server, request, reply);

	case 'M':
		return _handle_write_memory(server, request, reply);

	// case 'D':
	//     return _handle_detach(server, request, reply);

	case 'q':
		return _handle_query(server, request, reply);

	// case 'Q':
	//     return _handle_set(server, request, reply);

	// case 'v':
	//     return _handle_v_packet(server, request, reply);

	case 'D':
		return _handle_detach(server, request, reply);

	// case 'H': // thread indicator
	//     if (request.len == 1) break; // obligatory edge case prevention
	//     op++;
	//     goto parse;

	default: break;
	}

	// @TODO: handle overflow!!!!!!

	return _reply_empty(server, request, reply);
}

