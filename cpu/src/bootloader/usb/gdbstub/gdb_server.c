static gdb_command_result_t _reply_empty(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	(void)server;
	(void)request;
	reply->len = 0;
	return _send_reply();
}

static gdb_command_result_t _send_reply(void) {
	gdb_command_result_t result = {
		.send_reply      = true,
		.action          = GDB_ACTION_NONE,
		.protocol_change = GDB_PROTOCOL_UNCHANGED,
	};
	return result;
}

static gdb_command_result_t _reply_error(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply,
	u8                  err_code
) {
	(void)server;
	(void)request;

	if (reply->capacity < 3u) {
		reply->len      = 0u;
		reply->overflow = true;
		return _send_reply();
	}

	reply->len  = 3;
	reply->data[0] = 'E';
	reply->data[1] = hex_digit(err_code >> 4);
	reply->data[2] = hex_digit(err_code);
	return _send_reply();
}

