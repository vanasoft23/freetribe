static gdb_command_result_t _handle_query(
	gdb_server_t       *server,
	gdb_request_t       request,
	gdb_reply_writer_t *reply
) {
	if (buf_starts_with_cstr(request.data, request.len, "qSupported")) {

		const char *str = "PacketSize=4000;qXfer:features:read+";
		_reply_put_str(reply, str);

	}
	else if (buf_starts_with_cstr(request.data, request.len, "qXfer:features:read:target.xml")) {

		_reply_put(reply, 'l');
		_reply_put_buf(reply, gdb_target_xml, gdb_target_xml_len);

	} else if (buf_starts_with_cstr(request.data, request.len, "qRcmd")) {
		
		const u8 *cursor = request.data + 5;
		const u8 *end    = request.data + request.len;

		if ((cursor == end)   ||
			(*cursor++ != ',') ||
			(cursor == end)) {
			return _reply_error(server, request, reply, 0x01);
		}

		u32 encoded_length = (u32)(end - cursor);
		if (((encoded_length & 1u) != 0u) ||
			((encoded_length / 2u) > reply->capacity)) {
			return _reply_error(server, request, reply, 0x01);
		}

		u32 decoded_length = encoded_length / 2u;
		for (u32 i = 0u; i < decoded_length; ++i) {
			int high = hex_nibble(cursor[i * 2u]);
			int low  = hex_nibble(cursor[i * 2u + 1u]);
			if ((high < 0) || (low < 0)) {
				return _reply_error(server, request, reply, 0x01);
			}

			reply->data[i] = (u8)((high << 4) | low);
		}

		return _handle_monitor_command(
			server,
			reply->data,
			decoded_length,
			request,
			reply
		);
	}

	return _send_reply();
}



